// Package testkit 是 M0.5 建的可复用测试基础设施（development-plan §4.1 M0.5、
// 10 §11.1「领域/引擎」分层）：脚本化模型、事件记录器、假时钟、确定性 id、
// 临时工作区、交互桩与空目录。M1 的引擎/存储/provider 测试直接复用这些替身。
//
// 设计口径：
//   - 每个替身只实现 internal/ports 里的一个端口，语义与端口注释逐条对齐；
//   - 每个替身在文件头注明它守的是哪条不变量（INV-x，02 §5.3 的表）；
//   - 只用标准库：不引入 testify 等测试依赖（10 §11.2 门禁保持轻量）；
//   - 一律可并行使用：替身内部自带互斥，不监听端口、不共享进程级单例。
//
// INV-2（02 §5.3）：每个端口都要有生产实现与测试替身，不允许 nil 端口。
// 本包提供的是「测试替身」一侧；编译期断言集中在 doubles.go，
// `go build ./...` 就会因为替身不再满足端口而失败，而不是等到 M1 运行期。
