// 变量段：把 Token 机械映射为 CSS 变量与字型工具类
// ---------------------------------------------------------------------------

func cssVars(t Tokens) string {
	var b strings.Builder
	b.WriteString(":root{\n")
	b.WriteString(fmt.Sprintf("  --ds-font: %s;\n  --ds-grid: %dpx;\n", t.Type.Family, t.Grid))
	names := sortedStrKeys(t.Colors)
	for _, name := range names {
		b.WriteString(fmt.Sprintf("  --ds-color-%s: %s;\n", cssName(name), t.Colors[name].Value))
	}
	for _, name := range sortedIntKeys(t.Spacing) {
		b.WriteString(fmt.Sprintf("  --ds-space-%s: %dpx;\n", cssName(name), t.Spacing[name]))
	}
	for _, name := range sortedIntKeys(t.Radius) {
		b.WriteString(fmt.Sprintf("  --ds-radius-%s: %dpx;\n", cssName(name), t.Radius[name]))
	}
	for _, name := range sortedStrKeys(t.Shadows) {
		b.WriteString(fmt.Sprintf("  --ds-shadow-%s: %s;\n", cssName(name), t.Shadows[name]))
	}
	for _, name := range sortedStrKeys(t.Motion) {
		b.WriteString(fmt.Sprintf("  --ds-motion-%s: %s;\n", cssName(name), t.Motion[name]))
	}
	levels := sortedStrKeys(t.Type.Levels)
	for _, lv := range levels {
		spec := t.Type.Levels[lv]
		b.WriteString(fmt.Sprintf("  --ds-type-%s: %dpx/%.2f %s;\n", cssName(lv), spec.Size, spec.LineHeight, weightName(spec.Weight)))
		b.WriteString(fmt.Sprintf("  --ds-fs-%s: %dpx;\n", cssName(lv), spec.Size))
	}
	if len(levels) > 0 {
		// 最小字号（按尺寸取，而非字母序）：徽标等微型文本的规范引用位
		minSize := t.Type.Levels[levels[0]].Size
		for _, lv := range levels {
			if s := t.Type.Levels[lv].Size; s < minSize {
				minSize = s
			}
		}
		b.WriteString(fmt.Sprintf("  --ds-fs-min: %dpx;\n", minSize))
	}
	b.WriteString("}\n")
	// 字型工具类
	b.WriteString(".ds-t{font-family:var(--ds-font)}\n")
	for _, lv := range levels {
		b.WriteString(fmt.Sprintf(".ds-t-%s{font-size:%dpx;font-weight:%d;line-height:%.2f;%s}\n",
			cssName(lv), t.Type.Levels[lv].Size, t.Type.Levels[lv].Weight, t.Type.Levels[lv].LineHeight,
			letterSpacing(t.Type.Levels[lv])))
	}
	return b.String()
}

func letterSpacing(spec TypeSpec) string {
	if spec.LetterSpacing == 0 {
		return ""
	}
	return fmt.Sprintf("letter-spacing:%.2fpx;", spec.LetterSpacing)
}

func weightName(w int) string {
	if w == 0 {
		return "400"
	}
	return fmt.Sprint(w)
}

// cssName 把语义名转为 CSS 变量片段（保留下划线与连字符）。
func cssName(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		switch {
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9', r == '-', r == '_':
			b.WriteRune(r)
		default:
			b.WriteRune('-')
		}
	}
	return b.String()
}

