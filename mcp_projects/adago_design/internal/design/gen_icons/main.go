// Command gen_icons 由 internal/design 的图标注册表生成画布 UI 用的 icons.js，
// 保证「预览侧图标」与「画布侧图标」永远同源。
//
// 用法：go generate ./internal/design（见 icons.go 顶部的 go:generate 指令）
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"adagodesign/internal/design"
)

func main() {
	out := flag.String("out", "", "输出路径（icons.js）")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "gen_icons: -out is required")
		os.Exit(1)
	}

	paths := map[string]string{}
	for _, ic := range design.Icons() {
		paths[ic.Name] = ic.Body
	}
	raw, err := json.Marshal(paths)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen_icons: marshal paths:", err)
		os.Exit(1)
	}
	sprite, err := json.Marshal(design.IconSprite())
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen_icons: marshal sprite:", err)
		os.Exit(1)
	}

	var names []string
	for n := range paths {
		names = append(names, n)
	}
	sort.Strings(names)
	nameJSON, err := json.Marshal(names)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen_icons: marshal names:", err)
		os.Exit(1)
	}

	body := "// Code generated by internal/design/gen_icons; DO NOT EDIT.\n" +
		"// 数据源：internal/design/icon_paths.go（与预览文档共用一份图标库）。\n" +
		"/* eslint-disable */\n" +
		"(function () {\n" +
		"  var PATHS = " + string(raw) + ";\n" +
		"  var SPRITE = " + string(sprite) + ";\n" +
		"  var NAMES = " + string(nameJSON) + ";\n" +
		"  window.DSIcons = { paths: PATHS, sprite: SPRITE, names: NAMES,\n" +
		"    has: function (n) { return Object.prototype.hasOwnProperty.call(PATHS, n); } };\n" +
		"  window.icon = function (name, size, cls) {\n" +
		"    if (!window.DSIcons.has(name)) return \"\";\n" +
		"    var s = size || 20;\n" +
		"    return '<svg class=\"ds-icon ds-icon--' + s + (cls ? ' ' + cls : '') + '\" aria-hidden=\"true\">' +\n" +
		"      '<use href=\"#ds-ic-' + name + '\"/></svg>';\n" +
		"  };\n" +
		"  function inject() {\n" +
		"    if (document.getElementById('ds-icon-sprite') || !document.body) return;\n" +
		"    var box = document.createElement('div');\n" +
		"    box.id = 'ds-icon-sprite';\n" +
		"    box.style.cssText = 'position:absolute;width:0;height:0;overflow:hidden';\n" +
		"    box.innerHTML = SPRITE;\n" +
		"    document.body.appendChild(box);\n" +
		"  }\n" +
		"  if (document.body) inject();\n" +
		"  else document.addEventListener('DOMContentLoaded', inject);\n" +
		"})();\n"

	if err := os.MkdirAll(filepath.Dir(*out), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "gen_icons: mkdir:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(body), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "gen_icons: write:", err)
		os.Exit(1)
	}
	fmt.Printf("gen_icons: %d icons -> %s\n", len(paths), *out)
}
