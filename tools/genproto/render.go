package main

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// render 生成 internal/proto/methods_gen.go 的源码（未经 gofmt）。
func render(d *document) ([]byte, error) {
	var buf bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&buf, format, args...) }

	w("// Code generated by tools/genproto from %s. DO NOT EDIT.\n", defaultSpec)
	w("// 生成命令：go generate ./...   （CI 会用 go generate 后的 git diff 检查同步）\n\n")
	w("package %s\n\n", pkgName)
	w("import (\n\t\"fmt\"\n\t\"sort\"\n)\n\n")
	w("// 说明（来自协议源 conventions.notes）：\n")
	for _, n := range d.Conventions.Notes {
		w("//   - %s\n", n)
	}
	w("//\n// JSON-RPC 保留码由传输层负责：%s\n\n", intsToComment(d.reservedCodes()))

	// ---- 版本与传输常量 ----
	w("// 协议源文件的结构版本、Gateway↔Core 协议版本与插件 API 版本（握手与漂移检查用）。\n")
	w("const (\n")
	w("\tSchemaVersion = %d\n", d.SchemaVersion)
	w("\tProtoVersion  = %d\n", d.ProtoVersion)
	w("\tAPIVersion    = %q\n", d.APIVersion)
	w(")\n\n")

	w("// 传输层固定值（设计 8.1、8.3、7.4）。\n")
	w("const (\n")
	w("\tEncoding = %q\n", d.Transport.Encoding)
	w("\tMaxMessageBytes = %d\n", d.Transport.MaxMessageBytes)
	w("\tPingIntervalMS = %d\n", d.Transport.PingIntervalMS)
	w("\tPongTimeoutMS = %d\n", d.Transport.PongTimeoutMS)
	w("\tHandshakeTimeoutMS = %d\n", d.Transport.HandshakeTimeoutMS)
	w("\tEventBuffer = %d\n", d.Transport.EventBuffer)
	w("\tSnapshotFieldTruncateBytes = %d\n", d.Transport.SnapshotFieldTruncateBytes)
	w("\tDeltaMergeWindowMS = %d\n", d.Transport.DeltaMergeWindowMS)
	w("\tDeltaMaxLatencyMS = %d\n", d.Transport.DeltaMaxLatencyMS)
	w(")\n\n")

	w("// 标识与排序约定（设计 8.3、4.2）。\n")
	w("const (\n")
	w("\tThreadIDFormat  = %q\n", d.Conventions.ThreadIDFormat)
	w("\tEntryIDFormat   = %q\n", d.Conventions.EntryIDFormat)
	w("\tEventIDPrefix   = %q\n", d.Conventions.EventIDPrefix)
	w("\tTimestampFormat = %q\n", d.Conventions.TimestampFormat)
	w(")\n\n")
	w("var ItemKeyPrefixes = []string{%s}\n\n", quoteList(d.Conventions.ItemKeyPrefixes))

	// ---- 方法常量 ----
	w("// 方法名常量：唯一来源是 spec/proto.json，Core dispatch 与 Gateway 调用都引用它们。\n")
	w("const (\n")
	used := map[string]bool{}
	for _, m := range d.Methods {
		ident := methodIdent(m.Name)
		if used[ident] {
			return nil, fmt.Errorf("方法常量名冲突：%s（来自 %s）", ident, m.Name)
		}
		used[ident] = true
		w("\t%s = %q // %s\n", ident, m.Name, m.Summary)
	}
	w(")\n\n")

	// ---- 事件常量 ----
	w("// 事件名常量（JSON-RPC notification，无 id）。\n")
	w("const (\n")
	used = map[string]bool{}
	for _, e := range d.Events {
		ident := eventIdent(e.Name)
		if used[ident] {
			return nil, fmt.Errorf("事件常量名冲突：%s（来自 %s）", ident, e.Name)
		}
		used[ident] = true
		w("\t%s = %q // %s\n", ident, e.Name, e.Summary)
	}
	w(")\n\n")

	// ---- 错误码常量 ----
	w("// 应用错误码（设计 8.5）。JSON-RPC 标准码由传输层负责，不在这里。\n")
	w("const (\n")
	used = map[string]bool{}
	for _, c := range d.ErrorCodes {
		ident := errorIdent(c.Name)
		if used[ident] {
			return nil, fmt.Errorf("错误码常量名冲突：%s（来自 %s）", ident, c.Name)
		}
		used[ident] = true
		w("\t%s = %d // %s\n", ident, c.Code, c.Title)
	}
	w(")\n\n")

	// ---- 元数据表 ----
	w("// MethodMeta 是一个方法的派发元数据。\n")
	w("type MethodMeta struct {\n\tName string\n\tGroup string\n\tSummary string\n\tDirection string\n\tSince string\n\tIdempotent bool\n\tRequiresReadyInstance bool\n\tDefaultDisabled bool\n}\n\n")
	w("// Methods 按 spec/proto.json 的顺序列出全部方法，dispatch 覆盖率以此为分母。\n")
	w("var Methods = []MethodMeta{\n")
	for _, m := range d.Methods {
		w("\t{Name: %q, Group: %q, Summary: %q, Direction: %q, Since: %q, Idempotent: %v, RequiresReadyInstance: %v, DefaultDisabled: %v},\n",
			m.Name, m.Group, m.Summary, m.Direction, m.Since, m.Idempotent, m.RequiresReadyInstance, m.DefaultDisabled)
	}
	w("}\n\n")

	w("// Events 按 spec/proto.json 的顺序列出全部事件。\n")
	w("type EventMeta struct {\n\tName string\n\tScope string\n\tSummary string\n\tReplayable bool\n\tEntersModelContext bool\n}\n\n")
	w("var Events = []EventMeta{\n")
	for _, e := range d.Events {
		w("\t{Name: %q, Scope: %q, Summary: %q, Replayable: %v, EntersModelContext: %v},\n",
			e.Name, e.Scope, e.Summary, e.Replayable, e.EntersModelContext)
	}
	w("}\n\n")

	w("// ErrorMeta 是应用错误码的元数据；诊断码绑定在 internal/diag（词汇表唯一位置）。\n")
	w("type ErrorMeta struct {\n\tCode int\n\tName string\n\tTitle string\n\tRetryable bool\n\tTypical []string\n\tDiagnosticArea string\n}\n\n")
	w("var ErrorCodes = []ErrorMeta{\n")
	for _, c := range d.ErrorCodes {
		w("\t{Code: %d, Name: %q, Title: %q, Retryable: %v, Typical: []string{%s}, DiagnosticArea: %q},\n",
			c.Code, c.Name, c.Title, c.Retryable, quoteList(c.Typical), c.DiagnosticArea)
	}
	w("}\n\n")

	// ---- 查询函数 ----
	w("// AllMethodNames 返回全部方法名（协议顺序）。\n")
	w("func AllMethodNames() []string {\n\tout := make([]string, len(Methods))\n\tfor i, m := range Methods {\n\t\tout[i] = m.Name\n\t}\n\treturn out\n}\n\n")
	w("// AllEventNames 返回全部事件名（协议顺序）。\n")
	w("func AllEventNames() []string {\n\tout := make([]string, len(Events))\n\tfor i, e := range Events {\n\t\tout[i] = e.Name\n\t}\n\treturn out\n}\n\n")
	w("// LookupMethod 按名字找方法元数据。\n")
	w("func LookupMethod(name string) (MethodMeta, bool) {\n\tfor _, m := range Methods {\n\t\tif m.Name == name {\n\t\t\treturn m, true\n\t\t}\n\t}\n\treturn MethodMeta{}, false\n}\n\n")
	w("// LookupEvent 按名字找事件元数据。\n")
	w("func LookupEvent(name string) (EventMeta, bool) {\n\tfor _, e := range Events {\n\t\tif e.Name == name {\n\t\t\treturn e, true\n\t\t}\n\t}\n\treturn EventMeta{}, false\n}\n\n")
	w("// LookupError 按应用码找错误元数据。\n")
	w("func LookupError(code int) (ErrorMeta, bool) {\n\tfor _, c := range ErrorCodes {\n\t\tif c.Code == code {\n\t\t\treturn c, true\n\t\t}\n\t}\n\treturn ErrorMeta{}, false\n}\n\n")
	w("// ErrorByName 按名字找错误元数据。\n")
	w("func ErrorByName(name string) (ErrorMeta, bool) {\n\tfor _, c := range ErrorCodes {\n\t\tif c.Name == name {\n\t\t\treturn c, true\n\t\t}\n\t}\n\treturn ErrorMeta{}, false\n}\n\n")

	// 分组表（verify 与文档用）。
	w("// MethodsByGroup 按分组列出方法（分组名升序）。\n")
	w("var MethodsByGroup = map[string][]string{\n")
	groups := map[string][]string{}
	for _, m := range d.Methods {
		groups[m.Group] = append(groups[m.Group], m.Name)
	}
	for _, g := range sortedKeys(groups) {
		w("\t%q: {%s},\n", g, quoteList(groups[g]))
	}
	w("}\n\n")

	w("// Groups 返回全部方法分组（升序）。\n")
	w("func Groups() []string {\n\tout := make([]string, 0, len(MethodsByGroup))\n\tfor g := range MethodsByGroup {\n\t\tout = append(out, g)\n\t}\n\tsort.Strings(out)\n\treturn out\n}\n\n")

	w("// Counts 是协议数量；adag verify 拿它与设计文档的「核心数字」比对（design.md 文档约定）。\n")
	w("type Counts struct{ Methods, Events, ErrorCodes, Groups int }\n\n")
	w("func SpecCounts() Counts {\n\treturn Counts{Methods: len(Methods), Events: len(Events), ErrorCodes: len(ErrorCodes), Groups: len(MethodsByGroup)}\n}\n\n")

	w("// String 便于日志与页面展示错误码。\n")
	w("func (e ErrorMeta) String() string {\n\treturn fmt.Sprintf(\"%%s(%%d)\", e.Name, e.Code)\n}\n")

	return buf.Bytes(), nil
}

// intsToComment 把保留码列表渲染成注释片段。
func intsToComment(xs []int) string {
	if len(xs) == 0 {
		return "（未声明）"
	}
	parts := make([]string, len(xs))
	for i, x := range xs {
		parts[i] = fmt.Sprintf("%d", x)
	}
	return strings.Join(parts, ", ")
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func quoteList(items []string) string {
	parts := make([]string, len(items))
	for i, s := range items {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(parts, ", ")
}

// ident 把点分/下划线名字转成导出的 Go 标识符，并加前缀。
func ident(prefix, name string) string {
	segments := strings.FieldsFunc(name, func(r rune) bool {
		return r == '.' || r == '_' || r == '-' || r == '/'
	})
	var b strings.Builder
	b.WriteString(prefix)
	for _, seg := range segments {
		b.WriteString(titleCase(seg))
	}
	out := b.String()
	if out == "" {
		return prefix + "Unknown"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = prefix + out
	}
	return out
}

func titleCase(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	// 常见首字母缩写保持全大写形状：id → Id（Go 惯例里 Id 也可接受，这里刻意不做例外，
	// 以保证名字与协议字符串可逆映射，便于门禁反查）。
	return strings.ToUpper(string(r[0])) + string(r[1:])
}

func methodIdent(name string) string { return ident("Method", name) }
func eventIdent(name string) string  { return ident("Evt", strings.TrimPrefix(name, "evt.")) }
func errorIdent(name string) string  { return ident("Code", name) }
